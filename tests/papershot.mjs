import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--disable-background-networking'] });
const page = await b.newPage({ viewport: { width: 1440, height: 860 } });
await page.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
await page.goto('file:///home/claude/waylight/dist/test.html?debug', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.WL && WL.snapshot().baked, null, { timeout: 60000 });
await page.evaluate(() => localStorage.clear());
await page.click('#btnNew'); await page.waitForTimeout(150); await page.click('#btnBegin'); await page.waitForTimeout(250);
await page.click('#briefGo'); await page.waitForTimeout(200); await page.click('#cgBegin'); await page.waitForTimeout(600);
await page.evaluate(() => { WL.calm(); S.weather.state = 'clear'; S.weather.t = 9999; S.time = 60; for (let i = 0; i < 15 && S.cine; i++) WL.skipCine && WL.skipCine();
  S.stations.elm.connected = true; S.stations.elm.met = true; S.stations.elm.litT = 1; State.refreshSources(); World.rebuildLight();
  WL.tp('haven'); S.moveTo = null; UI.openStation('haven');
});
await page.waitForTimeout(700);
await page.screenshot({ path: '/tmp/paper_terminal.png' });
await page.evaluate(() => { document.getElementById('stationClose').click(); });
await page.waitForTimeout(300);
// the station slab + pixel shadows close up
await page.evaluate(() => Render.setZoom(1.9));
await page.waitForTimeout(700);
await page.screenshot({ path: '/tmp/paper_station.png', clip: { x: 460, y: 100, width: 520, height: 440 } });
await page.evaluate(() => Render.setZoom(null));
console.log('done');
await b.close();
